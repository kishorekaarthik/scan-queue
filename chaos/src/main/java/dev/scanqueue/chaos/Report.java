package dev.scanqueue.chaos;

import com.fasterxml.jackson.databind.JsonNode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Turns results/&lt;mode&gt;/run-*.json into summary.md, and optionally splices it
 * into the README between {@code <!-- chaos:<mode>:begin -->} / {@code end} markers.
 * The README never contains a hand-typed result number.
 */
final class Report {

    private Report() {
    }

    static void write(Path dir, Path readme) throws IOException {
        List<JsonNode> runs = new ArrayList<>();
        try (Stream<Path> files = Files.list(dir)) {
            for (Path p : files.filter(f -> f.getFileName().toString().matches("run-\\d+\\.json")).sorted().toList()) {
                runs.add(ChaosMain.JSON.readTree(p.toFile()));
            }
        }
        if (runs.isEmpty()) {
            throw new IllegalStateException("no run-*.json in " + dir);
        }
        String mode = runs.get(0).path("mode").asText("final");
        String md = render(runs, dir);
        Files.writeString(dir.resolve("summary.md"), md, StandardCharsets.UTF_8);
        if (readme != null) {
            splice(readme, mode, md);
        }
    }

    static String render(List<JsonNode> runs, Path dir) {
        JsonNode cfg = runs.get(0).path("config");
        StringBuilder s = new StringBuilder();
        s.append("_Generated by `java -jar chaos/target/chaos.jar report --out ").append(dir.toString().replace('\\', '/'))
                .append("` from ").append(runs.size()).append(" run files. ")
                .append(cfg.path("files").asText()).append(" files per run (every ").append(cfg.path("eicar_every").asText())
                .append("th is EICAR), ").append(cfg.path("workers").asText()).append(" workers, 1 sender, webhook response delay ")
                .append(cfg.path("webhook_delay_ms").asText()).append(" ms._\n\n");

        s.append("**Correctness**\n\n");
        table(s, runs, new String[][]{
                {"jobs", "jobs"}, {"verdicts", "verdicts"}, {"malicious", "malicious"},
                {"alerts accepted", "alerts_accepted"}, {"duplicates rejected", "duplicates_rejected"},
                {"fenced-out writes", "fenced_writes"}, {"job lease expiries", "lease_expiries"},
                {"alert lease expiries", "alert_lease_expiries"}, {"dead jobs", "dead_jobs"}, {"dead alerts", "dead_alerts"},
                {"all checks", "all_checks_pass"}}, true);

        s.append("\n**Performance and recovery** (latency = upload to verdict; recovery = kill to last interrupted item finished elsewhere; DB clock)\n\n");
        table(s, runs, new String[][]{
                {"jobs/sec", "throughput_jobs_per_sec"}, {"p50 latency ms", "latency_p50_ms"},
                {"p95 latency ms", "latency_p95_ms"}, {"worker recovery p50 ms", "recovery_worker_p50_ms"},
                {"worker recovery max ms", "recovery_worker_max_ms"}, {"alert recovery p50 ms", "recovery_alert_p50_ms"},
                {"alert recovery max ms", "recovery_alert_max_ms"}, {"peak container MB", "memory_peak_mb"}}, false);

        s.append("\n**Chaos** (observed = lease seen held in the DB right before SIGKILL; confirmed = that container's lease later expired, i.e. the kill interrupted real work; "
                + "pauses = `docker pause` for lease + 3 s while holding a lease, then unpause: the zombie whose late write must be fenced)\n\n");
        table(s, runs, new String[][]{
                {"worker kills", "kills_worker"}, {"worker kills holding a lease (observed)", "kills_worker_holding_lease_observed"},
                {"worker kills holding a lease (confirmed)", "kills_worker_holding_lease_confirmed"},
                {"sender kills", "kills_sender"}, {"sender kills with alert in flight (observed)", "kills_sender_alert_in_flight_observed"},
                {"sender kills with alert in flight (confirmed)", "kills_sender_alert_in_flight_confirmed"},
                {"webhook restarts", "webhook_restarts"}, {"webhook restarts with alert in flight (observed)", "webhook_restarts_alert_in_flight_observed"},
                {"worker pauses (zombies)", "pauses_worker"}, {"worker pauses whose lease was reclaimed", "pauses_worker_lease_reclaimed"},
                {"sender pauses (zombies)", "pauses_sender"}, {"sender pauses whose lease was reclaimed", "pauses_sender_lease_reclaimed"},
                {"heartbeats that found the lease gone", "lease_lost_heartbeats"},
                {"unattributed lease expiries", "lease_expiries_unattributed"},
                {"upload client retries", "upload_client_retries"}}, true);

        s.append("\n**Pass/fail checks**\n\n| check |");
        for (JsonNode r : runs) s.append(" r").append(r.path("run").asInt()).append(" |");
        s.append("\n|---|");
        for (int i = 0; i < runs.size(); i++) s.append(":-:|");
        s.append('\n');
        Map<String, List<String>> checks = new LinkedHashMap<>();
        for (JsonNode r : runs) {
            for (JsonNode c : r.path("checks")) {
                checks.computeIfAbsent(c.path("name").asText(), k -> new ArrayList<>())
                        .add(c.path("pass").asBoolean() ? "PASS" : "**FAIL**");
            }
        }
        checks.forEach((name, vals) -> s.append("| ").append(name).append(" | ").append(String.join(" | ", vals)).append(" |\n"));

        List<String> notes = new ArrayList<>();
        for (JsonNode r : runs) {
            for (JsonNode c : r.path("checks")) {
                if (!c.path("pass").asBoolean()) {
                    notes.add("- run " + r.path("run").asInt() + ", " + c.path("name").asText() + ": " + c.path("detail").asText());
                }
            }
            for (JsonNode d : r.path("dead_items")) {
                notes.add("- run " + r.path("run").asInt() + " dead " + d.path("kind").asText() + " " + d.path("id").asText()
                        + " after " + d.path("attempts").asInt() + " attempts: " + d.path("last_error").asText());
            }
            if (r.path("aborted").asBoolean()) {
                notes.add("- run " + r.path("run").asInt() + " ABORTED: " + r.path("abort_reason").asText());
            }
        }
        if (!notes.isEmpty()) {
            s.append("\n**Failures and dead items**\n\n").append(String.join("\n", notes)).append('\n');
        }
        return s.toString();
    }

    /** One row per metric, one column per run, plus a total or min/median/max column. */
    private static void table(StringBuilder s, List<JsonNode> runs, String[][] rows, boolean total) {
        s.append("| metric |");
        for (JsonNode r : runs) s.append(" r").append(r.path("run").asInt()).append(" |");
        s.append(total ? " total |" : " min / median / max |").append("\n|---|");
        for (int i = 0; i <= runs.size(); i++) s.append("--:|");
        s.append('\n');
        for (String[] row : rows) {
            s.append("| ").append(row[0]).append(" |");
            List<Double> vals = new ArrayList<>();
            boolean bool = false;
            for (JsonNode r : runs) {
                JsonNode v = r.path(row[1]);
                if (v.isBoolean()) {
                    bool = true;
                    s.append(v.asBoolean() ? " PASS" : " **FAIL**").append(" |");
                } else {
                    s.append(' ').append(fmt(v)).append(" |");
                    if (v.isNumber()) vals.add(v.asDouble());
                }
            }
            if (bool) {
                long pass = runs.stream().filter(r -> r.path(row[1]).asBoolean()).count();
                s.append(' ').append(pass).append('/').append(runs.size()).append(" |\n");
            } else if (vals.isEmpty()) {
                s.append(" – |\n");
            } else if (total) {
                s.append(' ').append(num(vals.stream().mapToDouble(Double::doubleValue).sum())).append(" |\n");
            } else {
                List<Double> sorted = vals.stream().sorted().toList();
                s.append(' ').append(num(sorted.get(0))).append(" / ").append(num(sorted.get(sorted.size() / 2)))
                        .append(" / ").append(num(sorted.get(sorted.size() - 1))).append(" |\n");
            }
        }
    }

    private static String fmt(JsonNode v) {
        if (v.isMissingNode() || v.isNull()) return "–";
        if (v.isNumber()) return num(v.asDouble());
        String t = v.asText();
        return t.equals("NaN") ? "–" : t;
    }

    private static String num(double d) {
        if (Double.isNaN(d)) return "–";
        return d == Math.rint(d) ? Long.toString((long) d) : String.format("%.1f", d);
    }

    static void splice(Path readme, String mode, String md) throws IOException {
        String begin = "<!-- chaos:" + mode + ":begin -->";
        String end = "<!-- chaos:" + mode + ":end -->";
        String text = Files.readString(readme, StandardCharsets.UTF_8);
        int b = text.indexOf(begin), e = text.indexOf(end);
        if (b < 0 || e < b) {
            throw new IllegalStateException("markers " + begin + " / " + end + " not found in " + readme);
        }
        String out = text.substring(0, b + begin.length()) + "\n" + md + "\n" + text.substring(e);
        Files.writeString(readme, out, StandardCharsets.UTF_8);
    }
}
