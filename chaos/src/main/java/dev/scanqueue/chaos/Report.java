package dev.scanqueue.chaos;

import com.fasterxml.jackson.databind.JsonNode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Turns results/&lt;mode&gt;/run-*.json into summary.md, and optionally splices it
 * into the README between {@code <!-- chaos:<mode>:begin -->} / {@code end} markers.
 * The README never contains a hand-typed result number.
 */
final class Report {

    private Report() {
    }

    static void write(Path dir, Path readme) throws IOException {
        List<JsonNode> runs = new ArrayList<>();
        try (Stream<Path> files = Files.list(dir)) {
            for (Path p : files.filter(f -> f.getFileName().toString().matches("run-\\d+\\.json")).sorted().toList()) {
                runs.add(ChaosMain.JSON.readTree(p.toFile()));
            }
        }
        if (runs.isEmpty()) {
            throw new IllegalStateException("no run-*.json in " + dir);
        }
        String mode = runs.get(0).path("mode").asText("final");
        String md = render(runs, dir);
        Files.writeString(dir.resolve("summary.md"), md, StandardCharsets.UTF_8);
        if (readme != null) {
            splice(readme, mode, md);
        }
    }

    static String render(List<JsonNode> runs, Path dir) {
        JsonNode cfg = runs.get(0).path("config");
        StringBuilder s = new StringBuilder();
        s.append("_Generated by `java -jar chaos/target/chaos.jar report --out ").append(dir.toString().replace('\\', '/'))
                .append("` from ").append(runs.size()).append(" run files. ")
                .append(cfg.path("files").asText()).append(" files per run (every ").append(cfg.path("eicar_every").asText())
                .append("th is EICAR), ").append(cfg.path("workers").asText()).append(" workers, 1 sender, webhook response delay ")
                .append(cfg.path("webhook_delay_ms").asText()).append(" ms._\n\n");

        s.append("**Correctness**\n\n");
        table(s, runs, new String[][]{
                {"jobs", "jobs"}, {"verdicts", "verdicts"}, {"malicious", "malicious"},
                {"alerts accepted", "alerts_accepted"}, {"duplicates rejected", "duplicates_rejected"},
                {"fenced-out writes", "fenced_writes"}, {"job lease expiries", "lease_expiries"},
                {"alert lease expiries", "alert_lease_expiries"}, {"dead jobs", "dead_jobs"}, {"dead alerts", "dead_alerts"},
                {"all checks", "all_checks_pass"}}, true);

        s.append("\n**Latency** (headline: processing = final claim to committed verdict. Queue wait = upload to first claim. "
                + "End to end = upload to verdict, which also includes time lost to crashes. DB clock)\n\n");
        table(s, runs, new String[][]{
                {"processing p50 ms", "processing_p50_ms"}, {"processing p95 ms", "processing_p95_ms"},
                {"queue wait p50 ms", "queue_wait_p50_ms"}, {"queue wait p95 ms", "queue_wait_p95_ms"},
                {"end-to-end p50 ms", "end_to_end_p50_ms"}, {"end-to-end p95 ms", "end_to_end_p95_ms"},
                {"jobs re-claimed after a crash/freeze", "jobs_reclaimed"},
                {"their first-to-final claim delay p50 ms", "crash_delay_p50_ms"},
                {"jobs/sec", "throughput_jobs_per_sec"}, {"peak container MB", "memory_peak_mb"}}, false);

        s.append("\n**Recovery** (per kill: from the SIGKILL to the last item it interrupted being finished elsewhere. "
                + "Segments: medians over interrupted items that were not interrupted again)\n\n");
        table(s, runs, new String[][]{
                {"worker recovery p50 ms", "recovery_worker_p50_ms"}, {"worker recovery max ms", "recovery_worker_max_ms"},
                {"job: kill -> lease expiry", "/recovery_worker_segments/p50_kill_to_lease_expiry_ms"},
                {"job: lease expiry -> reaped", "/recovery_worker_segments/p50_lease_expiry_to_reaped_ms"},
                {"job: reaped -> re-claimed", "/recovery_worker_segments/p50_reaped_to_reclaimed_ms"},
                {"job: re-claimed -> verdict", "/recovery_worker_segments/p50_reclaimed_to_done_ms"},
                {"alert recovery p50 ms", "recovery_alert_p50_ms"}, {"alert recovery max ms", "recovery_alert_max_ms"},
                {"alert: kill -> lease expiry", "/recovery_alert_segments/p50_kill_to_lease_expiry_ms"},
                {"alert: lease expiry -> reaped", "/recovery_alert_segments/p50_lease_expiry_to_reaped_ms"},
                {"alert: reaped -> re-claimed", "/recovery_alert_segments/p50_reaped_to_reclaimed_ms"},
                {"alert: re-claimed -> delivered", "/recovery_alert_segments/p50_reclaimed_to_done_ms"},
                {"alerts interrupted", "/recovery_alert_segments/items"},
                {"...of which interrupted again", "/recovery_alert_segments/items_interrupted_again"},
                {"...their kill -> delivered p50 ms", "/recovery_alert_segments/p50_total_interrupted_again_ms"}}, false);

        s.append("\n**Chaos** (observed = lease seen held in the DB right before SIGKILL; confirmed = that container's lease later expired, i.e. the kill interrupted real work; "
                + "pauses = `docker pause` for lease + 3 s while holding a lease, then unpause: the zombie whose late write must be fenced)\n\n");
        table(s, runs, new String[][]{
                {"worker kills", "kills_worker"}, {"worker kills holding a lease (observed)", "kills_worker_holding_lease_observed"},
                {"worker kills holding a lease (confirmed)", "kills_worker_holding_lease_confirmed"},
                {"sender kills", "kills_sender"}, {"sender kills with alert in flight (observed)", "kills_sender_alert_in_flight_observed"},
                {"sender kills with alert in flight (confirmed)", "kills_sender_alert_in_flight_confirmed"},
                {"webhook restarts", "webhook_restarts"}, {"webhook restarts with alert in flight (observed)", "webhook_restarts_alert_in_flight_observed"},
                {"worker pauses (zombies)", "pauses_worker"}, {"worker pauses whose lease was reclaimed", "pauses_worker_lease_reclaimed"},
                {"sender pauses (zombies)", "pauses_sender"}, {"sender pauses whose lease was reclaimed", "pauses_sender_lease_reclaimed"},
                {"heartbeats that found the lease gone", "lease_lost_heartbeats"},
                {"unattributed lease expiries", "lease_expiries_unattributed"},
                {"upload client retries", "upload_client_retries"}}, true);

        s.append("\n**Pass/fail checks**\n\n| check |");
        for (JsonNode r : runs) s.append(" r").append(r.path("run").asInt()).append(" |");
        s.append("\n|---|");
        for (int i = 0; i < runs.size(); i++) s.append(":-:|");
        s.append('\n');
        Map<String, List<String>> checks = new LinkedHashMap<>();
        for (JsonNode r : runs) {
            for (JsonNode c : r.path("checks")) {
                checks.computeIfAbsent(c.path("name").asText(), k -> new ArrayList<>())
                        .add(c.path("pass").asBoolean() ? "PASS" : "**FAIL**");
            }
        }
        checks.forEach((name, vals) -> s.append("| ").append(name).append(" | ").append(String.join(" | ", vals)).append(" |\n"));

        List<String> notes = new ArrayList<>();
        for (JsonNode r : runs) {
            for (JsonNode c : r.path("checks")) {
                if (!c.path("pass").asBoolean()) {
                    notes.add("- run " + r.path("run").asInt() + ", " + c.path("name").asText() + ": " + c.path("detail").asText());
                }
            }
            for (JsonNode d : r.path("dead_items")) {
                notes.add("- run " + r.path("run").asInt() + " dead " + d.path("kind").asText() + " " + d.path("id").asText()
                        + " after " + d.path("attempts").asInt() + " attempts: " + d.path("last_error").asText());
            }
            if (r.path("aborted").asBoolean()) {
                notes.add("- run " + r.path("run").asInt() + " ABORTED: " + r.path("abort_reason").asText());
            }
        }
        if (!notes.isEmpty()) {
            s.append("\n**Failures and dead items**\n\n").append(String.join("\n", notes)).append('\n');
        }
        return s.toString();
    }

    /** One row per metric, one column per run, plus a total or min/median/max column. */
    private static void table(StringBuilder s, List<JsonNode> runs, String[][] rows, boolean total) {
        s.append("| metric |");
        for (JsonNode r : runs) s.append(" r").append(r.path("run").asInt()).append(" |");
        s.append(total ? " total |" : " min / median / max |").append("\n|---|");
        for (int i = 0; i <= runs.size(); i++) s.append("--:|");
        s.append('\n');
        for (String[] row : rows) {
            s.append("| ").append(row[0]).append(" |");
            List<Double> vals = new ArrayList<>();
            boolean bool = false;
            for (JsonNode r : runs) {
                JsonNode v = field(r, row[1]);
                if (v.isBoolean()) {
                    bool = true;
                    s.append(v.asBoolean() ? " PASS" : " **FAIL**").append(" |");
                } else {
                    s.append(' ').append(fmt(v)).append(" |");
                    if (v.isNumber()) vals.add(v.asDouble());
                }
            }
            if (bool) {
                long pass = runs.stream().filter(r -> field(r, row[1]).asBoolean()).count();
                s.append(' ').append(pass).append('/').append(runs.size()).append(" |\n");
            } else if (vals.isEmpty()) {
                s.append(" – |\n");
            } else if (total) {
                s.append(' ').append(num(vals.stream().mapToDouble(Double::doubleValue).sum())).append(" |\n");
            } else {
                List<Double> sorted = vals.stream().sorted().toList();
                s.append(' ').append(num(sorted.get(0))).append(" / ").append(num(sorted.get(sorted.size() / 2)))
                        .append(" / ").append(num(sorted.get(sorted.size() - 1))).append(" |\n");
            }
        }
    }

    /**
     * README headline (block chaos:headline): totals and latency over results/final/run-*.json.
     * Sums are over all runs; latency cells are the median of the per-run values (range in brackets).
     */
    static void writeHeadline(Path finalDir, Path readme) throws IOException {
        List<JsonNode> runs = new ArrayList<>();
        try (Stream<Path> files = Files.list(finalDir)) {
            for (Path p : files.filter(f -> f.getFileName().toString().matches("run-\\d+\\.json")).sorted().toList()) {
                runs.add(ChaosMain.JSON.readTree(p.toFile()));
            }
        }
        if (runs.isEmpty()) throw new IllegalStateException("no run-*.json in " + finalDir);
        JsonNode cfg = runs.get(0).path("config");
        long pass = runs.stream().filter(r -> r.path("all_checks_pass").asBoolean()).count();
        StringBuilder s = new StringBuilder();
        s.append("_Generated by `java -jar chaos/target/chaos.jar headline --out ").append(finalDir.toString().replace('\\', '/'))
                .append("` from ").append(runs.size()).append(" runs x ").append(cfg.path("files").asText())
                .append(" files (").append(cfg.path("workers").asText()).append(" workers, 1 sender)._\n\n");
        s.append("| | total over ").append(runs.size()).append(" runs |\n|---|--:|\n");
        String[][] rows = {
                {"jobs uploaded and acknowledged", "uploads_acknowledged"}, {"verdicts", "verdicts"},
                {"**jobs lost** (acknowledged, no verdict)", "lost_jobs"},
                {"malicious (EICAR) jobs", "malicious"}, {"alerts accepted by the webhook", "alerts_accepted"},
                {"**missing alerts**", "missing_alerts"}, {"**duplicate alerts accepted**", "duplicate_alerts_accepted"},
                {"worker kills (`kill -9`)", "kills_worker"}, {"...confirmed to interrupt a live lease", "kills_worker_holding_lease_confirmed"},
                {"sender kills (`kill -9`)", "kills_sender"}, {"...confirmed to interrupt an alert in flight", "kills_sender_alert_in_flight_confirmed"},
                {"webhook kills + restarts", "webhook_restarts"},
                {"worker / sender freezes past the lease (zombies)", "pauses_worker"},
                {"zombie writes fenced out", "fenced_writes"}, {"duplicate deliveries rejected by webhook dedup", "duplicates_rejected"}};
        for (String[] row : rows) {
            double total = 0;
            for (JsonNode r : runs) total += field(r, row[1]).asDouble();
            if (row[1].equals("pauses_worker")) {
                for (JsonNode r : runs) total += r.path("pauses_sender").asDouble();
            }
            s.append("| ").append(row[0]).append(" | ").append(num(total)).append(" |\n");
        }
        s.append("| pass/fail checks passed | ").append(pass).append(" / ").append(runs.size()).append(" runs |\n");

        s.append("\n| latency (median of per-run values; range) | p50 | p95 |\n|---|--:|--:|\n");
        for (String[] l : new String[][]{
                {"**processing**: final claim to committed verdict", "processing"},
                {"queue wait: upload to first claim", "queue_wait"},
                {"end to end: upload to verdict", "end_to_end"}}) {
            s.append("| ").append(l[0]).append(" | ").append(medRange(runs, l[1] + "_p50_ms")).append(" | ")
                    .append(medRange(runs, l[1] + "_p95_ms")).append(" |\n");
        }
        long wall = runs.stream().mapToLong(r -> r.path("wall_clock_sec").asLong()).sum();
        double peak = runs.stream().mapToDouble(r -> r.path("memory_peak_mb").asDouble()).max().orElse(Double.NaN);
        s.append("\nChaos runtime ").append(Math.round(wall / 60.0)).append(" min for ").append(runs.size())
                .append(" runs (excluding stack start-up); peak container memory ").append(num(peak)).append(" MB.\n");
        splice(readme, "headline", s.toString());
    }

    private static String medRange(List<JsonNode> runs, String key) {
        List<Double> v = runs.stream().map(r -> r.path(key).asDouble()).sorted().toList();
        return num(v.get(v.size() / 2)) + " ms (" + num(v.get(0)) + "–" + num(v.get(v.size() - 1)) + ")";
    }

    /** results/ablation/{A..E}/run-*.json -> results/ablation/summary.md (+ README block chaos:ablation). */
    static void writeAblation(Path dir, Path readme) throws IOException {
        Map<String, List<JsonNode>> byVariant = new LinkedHashMap<>();
        for (String v : ChaosMain.VARIANTS.keySet()) {
            Path d = dir.resolve(v);
            if (!Files.isDirectory(d)) continue;
            List<JsonNode> runs = new ArrayList<>();
            try (Stream<Path> files = Files.list(d)) {
                for (Path p : files.filter(f -> f.getFileName().toString().matches("run-\\d+\\.json")).sorted().toList()) {
                    runs.add(ChaosMain.JSON.readTree(p.toFile()));
                }
            }
            if (!runs.isEmpty()) byVariant.put(v, runs);
        }
        if (byVariant.isEmpty()) throw new IllegalStateException("no variant results under " + dir);

        StringBuilder s = new StringBuilder();
        JsonNode cfg = byVariant.values().iterator().next().get(0).path("config");
        s.append("_Generated by `java -jar chaos/target/chaos.jar ablation-report --out ").append(dir.toString().replace('\\', '/'))
                .append("`. Each variant: ").append(byVariant.values().iterator().next().size()).append(" runs x ")
                .append(cfg.path("files").asText()).append(" files, same seeds and failure schedule. Cells: total (run 1 / run 2 / run 3)._\n\n");

        String[][] outcomes = {
                {"lost jobs", "lost_jobs"}, {"stuck jobs", "stuck_jobs"},
                {"duplicate/stale verdict writes accepted", "duplicate_or_stale_verdict_writes_accepted"},
                {"missing alerts", "missing_alerts"}, {"duplicate alerts accepted", "duplicate_alerts_accepted"},
                {"alerts for clean files", "alerts_for_non_malicious"}};
        s.append("**What breaks when each mechanism is removed**\n\n| variant |");
        for (String[] o : outcomes) s.append(' ').append(o[0]).append(" |");
        s.append(" checks passed |\n|---|");
        for (int i = 0; i <= outcomes.length; i++) s.append("--:|");
        s.append('\n');
        for (var e : byVariant.entrySet()) {
            s.append("| **").append(e.getKey()).append("** ").append(ChaosMain.VARIANT_NAMES.get(e.getKey())).append(" |");
            for (String[] o : outcomes) s.append(' ').append(cell(e.getValue(), o[1])).append(" |");
            long pass = e.getValue().stream().filter(r -> r.path("all_checks_pass").asBoolean()).count();
            s.append(' ').append(pass).append('/').append(e.getValue().size()).append(" |\n");
        }

        String[][] work = {
                {"second scans rejected by fencing", "second_verdict_writes_rejected"},
                {"duplicates rejected by webhook", "duplicates_rejected"},
                {"alerts dropped by worker", "alerts_dropped_by_worker"},
                {"worker kills (confirmed in lease)", "kills_worker_holding_lease_confirmed"},
                {"sender kills (confirmed in flight)", "kills_sender_alert_in_flight_confirmed"},
                {"worker pauses", "pauses_worker"}, {"sender pauses", "pauses_sender"},
                {"webhook restarts", "webhook_restarts"}};
        s.append("\n**Safety work done and failures injected** (same seeds; the schedule is randomized from the seed but "
                + "targets depend on live state, so counts differ slightly between variants)\n\n| variant |");
        for (String[] o : work) s.append(' ').append(o[0]).append(" |");
        s.append("\n|---|");
        for (int i = 0; i < work.length; i++) s.append("--:|");
        s.append('\n');
        for (var e : byVariant.entrySet()) {
            s.append("| **").append(e.getKey()).append("** |");
            for (String[] o : work) s.append(' ').append(cell(e.getValue(), o[1])).append(" |");
            s.append('\n');
        }

        s.append("\n**Failed checks**\n\n");
        boolean any = false;
        for (var e : byVariant.entrySet()) {
            for (JsonNode r : e.getValue()) {
                for (JsonNode c : r.path("checks")) {
                    if (!c.path("pass").asBoolean()) {
                        any = true;
                        s.append("- ").append(e.getKey()).append(" run ").append(r.path("run").asInt()).append(": ")
                                .append(c.path("name").asText()).append(": ").append(c.path("detail").asText()).append('\n');
                    }
                }
            }
        }
        if (!any) s.append("- none\n");

        Files.writeString(dir.resolve("summary.md"), s.toString(), StandardCharsets.UTF_8);
        if (readme != null) {
            splice(readme, "ablation", s.toString());
        }
    }

    private static String cell(List<JsonNode> runs, String key) {
        double total = 0;
        List<String> per = new ArrayList<>();
        for (JsonNode r : runs) {
            JsonNode v = field(r, key);
            per.add(fmt(v));
            if (v.isNumber()) total += v.asDouble();
        }
        return num(total) + " (" + String.join(" / ", per) + ")";
    }

    /** Plain key, or a JSON pointer (leading slash) into a nested object. */
    static JsonNode field(JsonNode r, String key) {
        return key.startsWith("/") ? r.at(key) : r.path(key);
    }

    private static String fmt(JsonNode v) {
        if (v.isMissingNode() || v.isNull()) return "–";
        if (v.isNumber()) return num(v.asDouble());
        String t = v.asText();
        return t.equals("NaN") ? "–" : t;
    }

    private static String num(double d) {
        if (Double.isNaN(d)) return "–";
        return d == Math.rint(d) ? Long.toString((long) d) : String.format("%.1f", d);
    }

    static void splice(Path readme, String mode, String md) throws IOException {
        String begin = "<!-- chaos:" + mode + ":begin -->";
        String end = "<!-- chaos:" + mode + ":end -->";
        String text = Files.readString(readme, StandardCharsets.UTF_8);
        int b = text.indexOf(begin), e = text.indexOf(end);
        if (b < 0 || e < b) {
            throw new IllegalStateException("markers " + begin + " / " + end + " not found in " + readme);
        }
        String out = text.substring(0, b + begin.length()) + "\n" + md + "\n" + text.substring(e);
        Files.writeString(readme, out, StandardCharsets.UTF_8);
    }
}
